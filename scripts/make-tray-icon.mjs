/**
 * Generates the macOS menu-bar (tray) template icon and inlines it as base64
 * into src/main/trayIcon.ts. A template image must be black + alpha only.
 *
 * The mark is the same "watchful eye" as the app icon, simplified to read at
 * 16px. Run: node scripts/make-tray-icon.mjs
 */
import { deflateSync } from 'node:zlib'
import { readFileSync, writeFileSync } from 'node:fs'

function crc32(buf) {
  let c
  const t = []
  for (let n = 0; n < 256; n++) {
    c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c >>> 0
  }
  let crc = 0xffffffff
  for (const b of buf) crc = t[(crc ^ b) & 0xff] ^ (crc >>> 8)
  return (crc ^ 0xffffffff) >>> 0
}
function chunk(type, data) {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const t = Buffer.from(type, 'ascii')
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(Buffer.concat([t, data])))
  return Buffer.concat([len, t, data, crc])
}

/** eye template: stroked lens + filled pupil */
function draw(nx, ny) {
  const R = 0.42
  const h = 0.235
  const t = 0.115
  const d1 = Math.hypot(nx - 0.5, ny - (0.5 - h))
  const d2 = Math.hypot(nx - 0.5, ny - (0.5 + h))
  const arc1 = Math.abs(d1 - R) <= t / 2 && d2 <= R + t / 2
  const arc2 = Math.abs(d2 - R) <= t / 2 && d1 <= R + t / 2
  const pupil = Math.hypot(nx - 0.5, ny - 0.5) <= 0.15
  return arc1 || arc2 || pupil
}

function render(size) {
  const SS = 4
  const N = size * SS
  const cov = new Float32Array(size * size)
  for (let y = 0; y < N; y++) {
    for (let x = 0; x < N; x++) {
      if (draw((x + 0.5) / N, (y + 0.5) / N)) {
        cov[((y / SS) | 0) * size + ((x / SS) | 0)] += 1
      }
    }
  }
  const raw = Buffer.alloc(size * (size * 4 + 1))
  let o = 0
  for (let y = 0; y < size; y++) {
    raw[o++] = 0
    for (let x = 0; x < size; x++) {
      const a = Math.min(1, cov[y * size + x] / (SS * SS))
      raw[o++] = 0
      raw[o++] = 0
      raw[o++] = 0
      raw[o++] = Math.round(a * 255)
    }
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(size, 0)
  ihdr.writeUInt32BE(size, 4)
  ihdr[8] = 8
  ihdr[9] = 6
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0))
  ])
}

const png16 = render(16)
const png32 = render(32)
const out = `// Auto-generated by scripts/make-tray-icon.mjs — a 16pt "watchful eye"
// template icon, inlined so the bundled app never depends on a file path
// (which breaks inside app.asar).
export const TRAY_ICON_16 = 'data:image/png;base64,${png16.toString('base64')}'
export const TRAY_ICON_32 = 'data:image/png;base64,${png32.toString('base64')}'
`
writeFileSync('src/main/trayIcon.ts', out)

// preview (not used by the app)
writeFileSync('/tmp/tray-preview.png', render(160))
